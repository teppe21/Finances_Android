package com.teppe21.finances.domain.model

import java.time.Instant
import java.time.LocalDate

enum class NotificationParseStatus {
    PARSED, IGNORED, NEEDS_REVIEW, FAILED
}

/**
 * Sanitized outcome codes. These are the only notification-derived values that are
 * persisted as diagnostics; raw titles and texts are never stored.
 */
enum class NotificationStatusCode(val parseStatus: NotificationParseStatus) {
    ACCEPTED_EXPENSE(NotificationParseStatus.PARSED),
    ACCEPTED_INCOME(NotificationParseStatus.PARSED),
    ACCEPTED_TRANSFER(NotificationParseStatus.PARSED),
    ACCEPTED_REFUND(NotificationParseStatus.PARSED),
    REJECTED_PROMOTIONAL(NotificationParseStatus.IGNORED),
    REJECTED_SECURITY_MESSAGE(NotificationParseStatus.IGNORED),
    REJECTED_UNSUPPORTED_PACKAGE(NotificationParseStatus.IGNORED),
    REJECTED_NON_TRANSACTION(NotificationParseStatus.IGNORED),
    REJECTED_MALFORMED_TRANSACTION(NotificationParseStatus.FAILED),
    DUPLICATE_EXISTING_TRANSACTION(NotificationParseStatus.IGNORED),
    PENDING_POSSIBLE_DUPLICATE(NotificationParseStatus.NEEDS_REVIEW),
    PENDING_ACCOUNT_REVIEW(NotificationParseStatus.NEEDS_REVIEW),
    PENDING_LOW_CONFIDENCE(NotificationParseStatus.NEEDS_REVIEW);

    companion object {
        fun fromName(value: String?): NotificationStatusCode? =
            values().firstOrNull { it.name == value }
    }
}

/**
 * In-memory view of a posted notification. It lives only for the duration of
 * processing and is never written to disk or logs.
 */
data class RawNotification(
    val packageName: String,
    val title: String? = null,
    val text: String? = null,
    val bigText: String? = null,
    val postedAt: Instant = Instant.now(),
    /** StatusBarNotification.key; used only inside a hashed fingerprint. */
    val notificationKey: String? = null
)

/** Persisted diagnostic record: package, timestamps and sanitized status only. */
data class NotificationEvent(
    val id: String,
    val packageName: String,
    val postedAt: Instant = Instant.now(),
    val sourceBank: String? = null,
    val processed: Boolean = false,
    val parseStatus: NotificationParseStatus = NotificationParseStatus.NEEDS_REVIEW,
    val transactionId: String? = null,
    val fingerprint: String? = null,
    val reasonCode: String? = null
) {
    val statusCode: NotificationStatusCode? get() = NotificationStatusCode.fromName(reasonCode)
}

data class ParsedNotificationTransaction(
    /** Signed: negative for money leaving the account. */
    val amountMinor: Long,
    val currency: String,
    val direction: TransactionDirection,
    val merchant: String?,
    /** Short description generated by the parser; never the raw notification text. */
    val description: String,
    val date: LocalDate,
    val occurredAt: Instant,
    /** Institution that most likely holds the account (e.g. the card issuer shown by a wallet). */
    val suggestedInstitution: String? = null,
    val cardLast4: String? = null,
    val confidence: Float = 0.9f
)
